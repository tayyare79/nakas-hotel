def svg(name, size=16, width="1.8", stroke="currentColor"):
    return (f'<svg width="{size}" height="{size}" viewBox="0 0 24 24" fill="none" stroke="{stroke}" '
            f'stroke-width="{width}" aria-hidden="true">{ICON[name]}</svg>')


ARROW = svg("arrow", 14, "2")


def srcset(key):
    return ", ".join(f"{v['src']} {v['w']}w" for v in M["photos"][key]["webp"])


def largest(key):
    return M["photos"][key]["webp"][-1]["src"]


def picture(key, alt, sizes, cls=None, eager=False):
    fb = M["photos"][key]["fallback"]
    cls_attr = f' class="{cls}"' if cls else ""
    load = 'fetchpriority="high"' if eager else 'loading="lazy" decoding="async"'
    return (f'<picture><source type="image/webp" srcset="{srcset(key)}" sizes="{sizes}">'
            f'<img src="{fb["src"]}" width="{fb["w"]}" height="{fb["h"]}" alt="{esc(alt)}"{cls_attr} {load}></picture>')


