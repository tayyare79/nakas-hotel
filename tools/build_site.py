def text(s):
    """Plain text of a translation string that may contain <br>/<em>."""
    return html.unescape(re.sub(r"\s+", " ", re.sub(r"<br\s*/?>", " ", re.sub(r"<(?!br)[^>]+>", "", s)))).strip()


