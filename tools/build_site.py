def page_jsonld(lang, page, title, desc):
    t = S[lang]
    url = abs_url(C.page_path(page, lang))
    webpage = {
        "@type": "WebPage", "@id": url + "#webpage", "url": url, "name": title, "description": desc,
        "inLanguage": C.LANG_META[lang]["hreflang"],
        "isPartOf": {"@id": C.BASE_URL + "/#website"},
        "about": {"@id": C.BASE_URL + "/#hotel"},
        "primaryImageOfPage": abs_url(M["og"]["src"]),
    }
    graph = [
        hotel_jsonld(lang, page == "rooms"),
        {"@type": "WebSite", "@id": C.BASE_URL + "/#website", "url": C.BASE_URL + "/", "name": "Nakas Hotel",
         "inLanguage": [C.LANG_META[l]["hreflang"] for l in C.LANGS]},
        webpage,
    ]
    if page != "home":
        webpage["breadcrumb"] = {"@id": url + "#breadcrumb"}
        graph.append({"@type": "BreadcrumbList", "@id": url + "#breadcrumb", "itemListElement": [
            {"@type": "ListItem", "position": 1, "name": t["crumb_home"], "item": abs_url(C.page_path("home", lang))},
            {"@type": "ListItem", "position": 2, "name": text(t[f"nav_{page}"]), "item": url},
        ]})
    data = json.dumps({"@context": "https://schema.org", "@graph": graph}, ensure_ascii=False, indent=1)
    return data.replace("</", "<\\/")


