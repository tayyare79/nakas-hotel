def sitemap():
    entries = []
    for page in PAGES:
        alts = "\n".join(f'    <xhtml:link rel="alternate" hreflang="{C.LANG_META[l]["hreflang"]}" '
                         f'href="{abs_url(C.page_path(page, l))}"/>' for l in C.LANGS)
        alts += (f'\n    <xhtml:link rel="alternate" hreflang="x-default" '
                 f'href="{abs_url(C.page_path(page, C.DEFAULT_LANG))}"/>')
        for lang in C.LANGS:
            entries.append(f"""  <url>
    <loc>{abs_url(C.page_path(page, lang))}</loc>
    <lastmod>{C.LASTMOD}</lastmod>
{alts}
  </url>""")
    body = "\n".join(entries)
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">
{body}
</urlset>
"""


def write(rel, content):
    path = ROOT / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    return rel


def main():
    builders = {"home": home_page, "rooms": rooms_page, "location": location_page}
    written = []
    for page in PAGES:
        for lang in C.LANGS:
            written.append(write(C.page_path(page, lang).lstrip("/") + "index.html", builders[page](lang)))
    written.append(write("404.html", not_found_page()))
    written.append(write("tr/index.html", redirect_page("/")))
    written.append(write("sitemap.xml", sitemap()))
    print("\n".join(written))


if __name__ == "__main__":
    main()
